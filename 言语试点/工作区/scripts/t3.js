const { chromium } = require('/opt/node22/lib/node_modules/playwright');
(async () => {
  const file = process.argv[2];
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
  const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = [];
  p.on('pageerror', e => errors.push('pageerror: ' + e.message));
  p.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
  await p.goto('file://' + file + '#20251231_30128270');
  await p.waitForSelector('article');
  const modeBtns = await p.$$eval('[data-mode]', els => els.map(e => e.textContent));
  await p.click('[data-mode="word"]');
  const blanks = await p.$$eval('button.blank', els => els.map(e => e.textContent));
  const tapesInWord = await p.$$eval('button.tape', els => els.length);
  await p.click('button.blank');
  await p.click('.pick button:nth-child(1)');
  const revealed = await p.$$eval('mark.wrev', els => els.map(e => e.textContent));
  await p.click('.check .chips button:nth-child(2)');
  const prog = await p.$eval('#prog', e => e.textContent);
  await p.keyboard.press(' ');
  const pickAfterSpace = await p.$$eval('.pick', els => els.length);
  await p.click('.pick button:nth-child(2)');
  await p.click('.checks .check >> nth=1 >> .chips button >> nth=0');
  await p.screenshot({ path: file.replace(/\.html$/, '_w1.png') });
  await p.reload(); await p.waitForSelector('article');
  const persistedMode = await p.$eval('[data-mode="word"]', e => e.getAttribute('aria-pressed'));
  const persistedRev = await p.$$eval('mark.wrev', els => els.length);
  // article without words falls back to sentence mode
  await p.goto('file://' + file + '#20251202_30117958'); await p.reload(); await p.waitForSelector('article');
  const fallbackTapes = await p.$$eval('button.tape', els => els.length);
  const fallbackBlanks = await p.$$eval('button.blank', els => els.length);
  await p.click('#go-stats'); await p.waitForSelector('.stats');
  const labels = await p.$$eval('.stat', els => els.map(e => e.textContent));
  const review = await p.$$eval('.review .it', els => els.map(e => e.textContent));
  await p.screenshot({ path: file.replace(/\.html$/, '_w2.png'), fullPage: true });
  const p2 = await b.newPage({ viewport: { width: 400, height: 800 }, colorScheme: 'dark' });
  await p2.goto('file://' + file + '#20260725_30170880'); await p2.waitForSelector('article');
  await p2.click('[data-mode="word"]').catch(() => {});
  const overflow = await p2.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  await p2.screenshot({ path: file.replace(/\.html$/, '_w3.png') });
  console.log(JSON.stringify({ modeBtns, blanks, tapesInWord, revealed, prog, pickAfterSpace, persistedMode, persistedRev, fallbackTapes, fallbackBlanks, labels, review, overflow, errors }, null, 1));
  await b.close();
})();
