def diffs(s): return [b - a for a, b in zip(s, s[1:])]
def show(seq, blank='（　）'): return '，'.join(blank if x is None else str(x) for x in seq)
def frac(x):
    x = F(x)
    return str(x.numerator) if x.denominator == 1 else f'$\\dfrac{{{x.numerator}}}{{{x.denominator}}}$'
def num(x):
    x = F(x)
    return str(x.numerator) if x.denominator == 1 else (f'{float(x):g}' if x.denominator in (2, 4, 5, 10) else frac(x))
