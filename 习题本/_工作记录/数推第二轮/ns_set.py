def diffs(s): return [b - a for a, b in zip(s, s[1:])]
def frac(x):
    x = F(x)
    return str(x.numerator) if x.denominator == 1 else f'$\\dfrac{{{x.numerator}}}{{{x.denominator}}}$'
def num(x):
    x = F(x)
    return str(x.numerator).replace('-', '−') if x.denominator == 1 else frac(x)
def show(seq, blank='（　）'): return '，'.join(blank if x is None else num(x) for x in seq)
def factorial(n): return 1 if n < 2 else n * factorial(n - 1)
