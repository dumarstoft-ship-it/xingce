Q = []

def add(kind, value, options, key, steps, traps, seq=None, given=None, stem=None, text=None, letter=None, groups=None):
    """options: list of option values (the answer among them); traps: [(value, why someone lands on it)];
    text: {value: printed form}; letter: fixed answer for non-numeric options (printed in the given order);
    groups: for 分组 questions, the complete groups and the last (incomplete) one, for ns_verify's formula search"""
    Q.append(dict(kind=kind, value=value, options=options, key=key, steps=steps, traps=traps, seq=seq,
                  given=given, stem=stem, text=text or {}, letter=letter, groups=groups))

