def add(kind, value, options, key, steps, traps, seq=None, given=None, stem=None, text=None, letter=None):
    """options: list of option values (the answer among them); traps: [(value, why someone lands on it)];
    text: {value: printed form} when the plain number is not how it should print; letter: fixed answer for
    non-numeric options (then options are printed in the given order)"""
    Q.append(dict(kind=kind, value=value, options=options, key=key, steps=steps, traps=traps, seq=seq,
                  given=given, stem=stem, text=text or {}, letter=letter))

