R = []
def chk(key, got, expect, opts=None, note=''):
    ok = (got == expect)
    if opts is not None:
        hits = [o for o in opts if o == got]
        ok = ok and len(hits) == 1
    R.append((key, ok, got, note))

def first_reach(total, rates, durs=None):
    """从0开始按 rates 循环（每段时长 durs，默认1），返回首次达到 total 的精确时刻；水位不低于0。"""
    lv = F(0); t = F(0); i = 0
    while t < 10 ** 5:
        r = F(rates[i % len(rates)]); d = F(1) if durs is None else F(durs[i % len(durs)])
        if r > 0 and lv + r * d >= total:
            return t + (total - lv) / r
        lv = max(F(0), lv + r * d); t += d; i += 1

def first_clear(start, dec):
    """存量 start，按 dec（每小时净减少量）循环，返回首次清零时刻。"""
    lv = F(start); t = F(0); i = 0
    while True:
        r = F(dec[i % len(dec)])
        if r > 0 and lv - r <= 0: return t + lv / r
        lv -= r; t += 1; i += 1

def clock(start_min, hours):
    m = start_min + hours * 60
    assert m.denominator == 1
    m = int(m); return f'{m // 60}:{m % 60:02d}'

