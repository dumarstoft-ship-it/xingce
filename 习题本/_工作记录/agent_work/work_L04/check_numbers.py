from fractions import Fraction as F
import itertools
ok=True
def chk(name, cond, info=''):
    global ok
    print(('OK  ' if cond else 'FAIL'), name, info); ok &= bool(cond)

# D3 他因+计算: 120->84 起; 半年封闭施工、期间车流为平时40%
eff = F(6) + F(6)*F(2,5)            # 有效通车"月当量"
chk('D3 事故率不变', F(84,120) == eff/12, f'eff={eff}, 84/120={F(84,120)}')
# D3 拆桥+计算: 600件/6h vs 720件/8h
r0, r1 = F(600,6), F(720,8)
chk('D3 时效率降10%', (r1-r0)/r0 == F(-1,10), f'{r0}->{r1}')
# D18 绝对数->率: 城市事故4倍, 通行量8倍
chk('D18 城市事故率为农村一半', F(4,8) == F(1,2))
# D18 增长率x基数: 甲前年=乙/10, 甲+100%, 乙+20%
a, b = F(1,10)*2, F(1)*F(6,5)
chk('D18 甲仍只有乙的1/6', a/b == F(1,6), f'{a}/{b}')
# D18 结构差异(辛普森): 甲 重症60%成功84%, 轻症40%成功99%; 乙 重症10%成功68%, 轻症90%成功98%
jia = F(60,100)*F(84,100) + F(40,100)*F(99,100)
yi  = F(10,100)*F(68,100) + F(90,100)*F(98,100)
chk('D18 甲总体90%', jia == F(90,100), str(float(jia)))
chk('D18 乙总体95%', yi == F(95,100), str(float(yi)))
chk('D18 分层甲均更高', F(84,100)>F(68,100) and F(99,100)>F(98,100))
# D31 浓缩洗衣液: 单价4倍, 用量1/2 -> 单次花费2倍
chk('D31 浓缩液单次花费2倍', F(4)*F(1,2) == 2)
# D38 电梯大修: 1.2万台 x 30万元 = 36亿元 > 5亿
chk('D38 大修资金36亿', 12000*300000 == 3_600_000_000)
# D38 兼职骑手: 人数3倍, 人均单量1/2 -> 接单占比60%
part = F(3)*F(1,2); full = F(1)
chk('D38 兼职接单占60%', part/(part+full) == F(3,5))
chk('D38 投诉率相同', F(60,100)/F(3,5) == F(40,100)/F(2,5))
# D38 火灾率: 甲24起/12万辆, 乙12起/4万辆
chk('D38 乙火灾率更高', F(24,12) < F(12,4), f'{F(24,12)} vs {F(12,4)} 起/万辆')
# D38 新增市场主体: 甲2000->3000, 乙30000->33000
chk('D38 增长率50%与10%', F(3000-2000,2000)==F(1,2) and F(33000-30000,30000)==F(1,10))
chk('D38 乙绝对增量是甲3倍', (33000-30000) == 3*(3000-2000))
# D31 绝对风险: 十万分之一 x3 = 十万分之三
chk('D31 相对3倍=十万分之三', F(1,100000)*3 == F(3,100000))
# D38 必要条件: "只有X才Y" 等价 Y->X; 判断哪种情形与之矛盾
contra = [(x,y) for x,y in itertools.product([0,1],[0,1]) if not ((not y) or x)]
chk('D38 只有X才Y 仅被(非X,且Y)推翻', contra == [(0,1)], f'矛盾情形(X,Y)={contra}')
print('ALL OK' if ok else 'SOME FAILED')
