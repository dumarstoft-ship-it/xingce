def main():
    inp = [json.loads(l) for l in open(BASE + "math_2.jsonl", encoding="utf-8") if l.strip()]
    if len(inp) != len(ROWS):
        sys.exit("row count mismatch: input %d vs rows %d" % (len(inp), len(ROWS)))
    out = []
    for d, r in zip(inp, ROWS):
        rid, kind, module, kaofa, tech, diff, fig, inc, note = r
        if d["id"] != rid:
            sys.exit("id mismatch: input %s vs row %s" % (d["id"], rid))
        rec = {
            "id": rid,
            "kind": kind,
            "module": module,
            "kaofa": kaofa,
            "technique": tech,
            "difficulty": diff,
            "needs_figure": fig,
            "incomplete": inc,
        }
        if note:
            rec["note"] = note
        out.append(rec)
    with open(BASE + "out_math_2.jsonl", "w", encoding="utf-8") as f:
        for rec in out:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")
    print("wrote", len(out))


if __name__ == "__main__":
    main()
