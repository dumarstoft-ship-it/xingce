# ================= 考法六 往返取物与接送 =================
def c():
    outs = set()
    for D in [F(6), F(9), F(15)]:            # 单位到出口的路程（千米）
        for c_ in [F(1, 2), F(2, 3), F(1)]:  # 车速（千米/分）
            T = D / c_
            depart = 480 - T                   # 以 0:00 为 0 分钟，平时 8:00=480 到出口
            meet = 440 + 32                    # 7:20 出发步行 32 分钟
            w = (D - c_ * (meet - depart)) / 32   # 步速由"32 分钟时遇车"确定
            assert w > 0
            # 检验：车与人确在 meet 时刻相遇
            assert c_ * (meet - depart) + w * 32 == D
            back = meet + c_ * (meet - depart) / c_
            outs.add((480 + T) - back)
    assert len(outs) == 1
    return outs.pop()
