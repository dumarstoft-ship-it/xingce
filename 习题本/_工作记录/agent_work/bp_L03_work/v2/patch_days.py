"""Patch the v2 copies of data_days_a/b/c.py (exact-match replacements, each must hit once)."""
import re, sys, os
HERE = os.path.dirname(os.path.abspath(__file__))


def patch(fname, reps):
    p = os.path.join(HERE, fname)
    s = open(p, encoding='utf-8').read()
    for old, new in reps:
        n = s.count(old)
        if n != 1:
            sys.exit('%s: expected 1 hit, got %d for: %s' % (fname, n, old[:80]))
        s = s.replace(old, new)
    open(p, 'w', encoding='utf-8').write(s)
    print(fname, 'patched', len(reps))


def cut_variant(fname, head):
    """Remove one V(...) entry that starts with `head` (from its line start through the line ending with "'),\n")."""
    p = os.path.join(HERE, fname)
    s = open(p, encoding='utf-8').read()
    i = s.find(head)
    assert i >= 0 and s.count(head) == 1, head
    start = s.rfind('\n', 0, i) + 1
    end = s.find("'),\n", i)
    # the V(...) may carry kwargs: find the first line end after the idea string that closes the call
    m = re.compile(r"\)\,\n").search(s, i)
    end = m.end()
    block = s[start:end]
    s = s[:start] + s[end:]
    open(p, 'w', encoding='utf-8').write(s)
    return block


