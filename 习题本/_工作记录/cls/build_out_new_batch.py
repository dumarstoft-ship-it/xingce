KINDS = {"数学运算", "数字推理", "逻辑", "图推", "定义", "类比", "其他"}
MMOD = {"M%02d" % i for i in range(1, 15)}
LMOD = {"L%02d" % i for i in range(1, 8)} | {"C%02d" % i for i in range(1, 6)}

rows = [json.loads(l) for l in open(os.path.join(D, "new_batch.jsonl"), encoding="utf-8")]
ids = [r["id"] for r in rows]
missing = [i for i in ids if i not in C]
extra = [k for k in C if k not in ids]
assert not missing and not extra, (missing, extra)

errs = []
out = []
for r in rows:
    kind, mod, kaofa, tech, diff, fig, inc, note, ans = C[r["id"]]
    if kind not in KINDS: errs.append((r["id"], "kind"))
    if kind == "数学运算" and mod not in MMOD: errs.append((r["id"], "mmod"))
    if kind == "逻辑" and mod not in LMOD: errs.append((r["id"], "lmod"))
    if kind not in ("数学运算", "逻辑") and mod is not None: errs.append((r["id"], "mod-not-null"))
    if len(kaofa) > 20: errs.append((r["id"], "kaofa>20", len(kaofa), kaofa))
    if len(tech) > 12: errs.append((r["id"], "tech>12", len(tech), tech))
    if diff not in (1, 2, 3): errs.append((r["id"], "diff"))
    if ans not in (None, "A", "B", "C", "D"): errs.append((r["id"], "ans"))
    if r["paper"] == "2026江苏" and ans is None: errs.append((r["id"], "JS ans missing"))
    if r["paper"] not in ("2026江苏", "2026贵州(3.14联考)") and ans is not None: errs.append((r["id"], "unexpected ans"))
    out.append({"id": r["id"], "kind": kind, "module": mod, "kaofa": kaofa, "technique": tech,
                "difficulty": diff, "needs_figure": fig, "incomplete": inc, "note": note,
                "answer_read": ans})
assert not errs, errs

with open(os.path.join(D, "out_new_batch.jsonl"), "w", encoding="utf-8") as f:
    for o in out:
        f.write(json.dumps(o, ensure_ascii=False) + "\n")

